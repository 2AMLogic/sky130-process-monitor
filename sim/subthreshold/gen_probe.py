#!/usr/bin/env python3
"""Generate probe_tb.spice and probe.request.json (gmin lowered to 1e-15 in the request: the ngspice default 1e-12 S x 0.9 V = 0.9 pA floors every Id below ~1 pA) (device subthreshold probe).

One DC sweep of a shared gate drive (Vg = |Vgs|, 0..0.6 V). Every probe device sees
|Vds| = 0.9 V (half of the 1.8 V nominal supply; fixed offset, not scaled with the supply).
Devices: the oscillator's own devices (nfet/pfet L=0.15 W=0.42 and 0.84; pfet_lvt L=0.50 W=0.42)
plus width neighbours straddling (pfet models have no bin below W=0.42, so 0.42 is the model's lower limit there) the model's W-bin edges at 0.42 and 0.84 um, so a jump in
Id/W across a bin edge shows up as a continuity failure. Reads no result; run via `klt sim`.
"""
import json, sys
VDS = 0.9
VG_POINTS = [0.0, 0.05, 0.15, 0.30]          # |Vgs| at which Id is recorded (V)
DEVS = []                               # (name, kind, model, L, W)
for kind, model, L, edge_ws in (
    ("n", "sky130_fd_pr__nfet_01v8", 0.15, (0.40, 0.41, 0.42, 0.43, 0.44, 0.82, 0.83, 0.84, 0.85, 0.86)),
    ("p", "sky130_fd_pr__pfet_01v8", 0.15, (0.42, 0.43, 0.44, 0.82, 0.83, 0.84, 0.85, 0.86)),
    ("l", "sky130_fd_pr__pfet_01v8_lvt", 0.50, (0.42, 0.43, 0.44, 0.82, 0.83, 0.84, 0.85, 0.86)),
):
    for w in edge_ws:
        DEVS.append(("%s_w%03d" % (kind, round(w * 100)), kind, model, L, w))

def tb():
    o = ["* DEVICE SUBTHRESHOLD PROBE (circuit body for `klt sim`; generated by gen_probe.py).",
         "* SIMULATION ONLY. |Vgs| swept by Vg; |Vds| = %.2f V on every device." % VDS,
         "Vdd vdd 0 1.8", "Vg vg 0 0",
         "Egp gp vdd vg 0 -1",                       # PMOS gate = Vdd - Vg  (|Vsg| = Vg)
         "Bdp dpref 0 V=V(vdd)-%.2f" % VDS]          # PMOS drain reference
    for name, kind, model, L, W in DEVS:
        a = "W=%g L=%g nf=1 mult=1" % (W, L)
        if kind == "n":
            o += ["Vd_%s d_%s 0 %.2f" % (name, name, VDS),
                  "XM_%s d_%s vg 0 0 %s %s" % (name, name, model, a)]
        else:
            o += ["Vd_%s d_%s dpref 0" % (name, name),
                  "XM_%s d_%s gp vdd vdd %s %s" % (name, name, model, a)]
    return "\n".join(o) + "\n"

def request(gmin=1e-15, abstol=None):
    opts = {"gmin": gmin}
    if abstol is not None:
        opts["abstol"] = abstol
    ms = []
    for name, *_ in DEVS:
        for vg in VG_POINTS:
            tag = "i%03d_%s" % (round(vg * 1000), name)
            ms.append({"name": tag, "unit": "A",
                       "spice": ".meas dc %s find i(Vd_%s) at=%g" % (tag, name, vg)})
        ms.append({"name": "s05_" + name, "unit": "mV/dec",
                   "spice": ".meas dc s05_%s param='100/log10(abs(i150_%s)/abs(i050_%s))'" % (name, name, name)})
        ms.append({"name": "s_" + name, "unit": "mV/dec",
                   "spice": ".meas dc s_%s param='150/log10(abs(i300_%s)/abs(i150_%s))'" % (name, name, name)})
    return {"netlist": "probe_tb.spice", "engine": "ngspice",
            "models": {"pdk": "sky130A", "lib": "libs.tech/ngspice/sky130.lib.spice"},
            "corners": {"process": ["tt", "ff", "ss", "sf", "fs"], "supply_v": {"vdd": [1.80]},
                        "temperature_c": [-40, 27, 125]},
            "analysis": {"kind": "dc", "args": "Vg 0 0.6 0.01"},
            "measurements": ms, "options": {"timeout_s": 200, "keep_artifacts": False, "ngspice_options": opts}}

if __name__ == "__main__":
    d = sys.argv[1] if len(sys.argv) > 1 else "."
    open(d + "/probe_tb.spice", "w").write(tb())
    open(d + "/probe.request.json", "w").write(json.dumps(request(), indent=2) + "\n")
    # gmin / abstol sweep variants (issue #44): same probe, one solver setting changed per request
    for tag, gm, at in (("gmin1e-17", 1e-17, None), ("gmin1e-18", 1e-18, None), ("gmin1e-15_abstol1e-18", 1e-15, 1e-18)):
        open(d + "/probe_%s.request.json" % tag, "w").write(json.dumps(request(gm, at), indent=2) + "\n")
