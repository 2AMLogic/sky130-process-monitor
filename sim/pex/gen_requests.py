"""Write sim/pex/requests/<osc>.json: the klt pex testbench requests (T1 item 7, analog; issue #32).

Each is the #29 45-cell grid request for the oscillator (sim/sensitivity/requests/grid_<osc>.json,
same analysis window, measurement, solver options and corner box) with only the testbench body
swapped for sim/pex/osc/tb_<osc>.spice (one .include, as klt pex requires). Deterministic.
Usage: python3 -I sim/pex/gen_requests.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SENS = os.path.join(os.path.dirname(HERE), "sensitivity", "requests")
OSCS = ["osc_hd", "osc_nmos", "osc_pmos", "osc_wire", "osc_subth"]

os.makedirs(os.path.join(HERE, "requests"), exist_ok=True)

# osc_hd: the extracted subcircuit's pin order follows the layout's label order (out en vss vdd) and
# `klt pex --pins` does not reorder it, while the schematic is `en out vdd vss`. klt pex reuses the
# testbench's X line byte-for-byte on both sides, so the schematic-side DUT file is a self-contained
# wrapper that presents the schematic under the extracted pin order. The design netlist is copied
# verbatim except for the subcircuit name (osc_hd -> osc_hd_sch); nothing else is edited.
with open(os.path.join(os.path.dirname(os.path.dirname(HERE)), "design", "osc_bank", "osc_hd.spice")) as f:
    core = f.read()
assert core.count(".subckt osc_hd ") == 1
core = core.replace(".subckt osc_hd ", ".subckt osc_hd_sch ")
with open(os.path.join(HERE, "osc", "osc_hd_dut.spice"), "w") as f:
    f.write("* GENERATED by sim/pex/gen_requests.py - do not edit. Schematic-side DUT for klt pex (osc_hd).\n")
    f.write("* design/osc_bank/osc_hd.spice, subckt renamed osc_hd_sch, wrapped under the extracted pin order.\n")
    f.write('.include "$PDK_ROOT/sky130A/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice"\n')
    f.write(core)
    f.write("\n.subckt osc_hd out en vss vdd\nXsch en out vdd vss osc_hd_sch\n.ends osc_hd\n")
for o in OSCS:
    with open(os.path.join(SENS, "grid_%s.json" % o)) as f:
        r = json.load(f)
    r["netlist"] = "../osc/tb_%s.spice" % o
    r["batch"] = dict(r.get("batch", {}), capacity_wait_s=600)
    with open(os.path.join(HERE, "requests", "%s.json" % o), "w") as f:
        json.dump(r, f, indent=2)
        f.write("\n")
